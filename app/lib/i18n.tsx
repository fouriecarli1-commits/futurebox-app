/**
 * English and Afrikaans.
 *
 * The Afrikaans here is deliberately not textbook Afrikaans. Nobody says
 * "genereer 'n musiekstuk" to a friend — they say "maak 'n liedjie". The
 * register to aim for is how someone talks about music in a car, not how a
 * manual is written, because a formal translation of a casual English app
 * reads stiffer than the English did and people switch back.
 *
 * A song is a "liedjie", not a "snit". "Snit" is in the dictionary and it is
 * what the music press prints, but read aloud in the app it lands as Dutch
 * rather than as how anybody speaks, which is the opposite of the register
 * above. It was used in 107 places and is now used in none.
 *
 * Two rules that keep it honest:
 *
 *   · Content is not translated. A podcast called "The Diary of a CEO" is
 *     called that in both languages; translating a title invents a thing that
 *     does not exist. Only the app's own words change.
 *   · Where a term has no natural Afrikaans word, the English word stays.
 *     "Remix", "podcast" and "AI" are what people actually say. Inventing
 *     "hermengsel" would be worse than borrowing.
 */

